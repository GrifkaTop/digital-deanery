export const homeDateKey = (year: number, month: number, day: number) => `${year}-${String(month + 1).padStart(2, "0")}-${String(day).padStart(2, "0")}`;
export const bulletinDate = (date: string) => new Date(`${date}T12:00:00Z`);
export const demoHomeDate = "2026-11-17";
const fullDate = new Intl.DateTimeFormat("ru-RU", { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" });
export function eventDateLabel(event: CampusEvent) {
  const start = bulletinDate(event.date);
  return event.endDate ? fullDate.formatRange(start, bulletinDate(event.endDate)) : fullDate.format(start);
}
